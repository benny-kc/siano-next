function arPlu(n, o) {
  const h = n % 100;
  let c;
  if (n === 0) c = "zero";
  else if (n === 1) c = "one";
  else if (n === 2) c = "two";
  else if (h >= 3 && h <= 10) c = "few";
  else if (h >= 11 && h <= 99) c = "many";
  else c = "other";
  return o[c] != null ? o[c] : o.other;
}

